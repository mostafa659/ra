"""Generates lib/core/audio_engine/scoring/qps_vocab.dart (ids/escapes derived from phoneme_vocab.json + scoring.py)."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import scoring as S
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
esc = lambda c: "".join("\\u%04x" % ord(x) for x in c)
ids = lambda s: [S.CID[c] for c in s]
groups = [ids(g) for g in S.CONFUSABLE]
out = f"""// GENERATED by tools/scoring_ref/gen_dart_consts.py -- do not edit by hand.
// Muaalem-mini QPS alphabet (43 classes, id 0 = CTC blank) and class groups mirrored from scoring.py.

const int kQpsBlank = 0;
const int kQpsClasses = {len(S.VOCAB)};

const List<String> kQpsVocab = <String>[
{chr(10).join("  '" + (esc(c) if c != "[PAD]" else "[PAD]") + "'," for c in S.VOCAB)}
];

const List<int> kHarakatIds = <int>{ids(S.HARAKAT)};
const List<int> kMaddIds = <int>{sorted(ids("".join(S.MADD_SYMS)))};
const List<int> kGhunnaIds = <int>{ids("نںمۜ")};
const List<List<int>> kConfusableIds = <List<int>>{groups};
"""
open(os.path.join(ROOT, "lib/core/audio_engine/scoring/qps_vocab.dart"), "w").write(out)
